        private static readonly (string Name, string Description, string[] Children)[] Parsed =
            Lines.Select(line =>
            {
                var parts = line.Split('|');
                return (parts[0].Trim(), parts[1].Trim(),
                        parts[2].Split(';', StringSplitOptions.RemoveEmptyEntries)
                                .Select(name => name.Trim()).ToArray());
            }).ToArray();

        public static IReadOnlyList<string> Roots { get; } = Parsed.Select(x => x.Name).ToArray();

        /// <summary>Підкатегорії напряму в порядку макета; порожньо, якщо напряму немає в дереві.</summary>
        public static IReadOnlyList<string> Children(string root)
        {
            var index = IndexOfRoot(root);
            return index < 0 ? Array.Empty<string>() : Parsed[index].Children;
        }

        public static string Description(string root)
        {
            var index = IndexOfRoot(root);
            return index < 0 ? "" : Parsed[index].Description;
        }

        /// <summary>Місце напряму в бічному меню; невідомі йдуть у кінець.</summary>
        public static int RootOrder(string name)
        {
            var index = IndexOfRoot(name);
            return index < 0 ? int.MaxValue : index;
        }

        /// <summary>Місце плитки в панелі напряму; невідомі йдуть у кінець.</summary>
        public static int ChildOrder(string root, string name)
        {
            var children = Children(root);
            for (var i = 0; i < children.Count; i++)
            {
                if (SameName(children[i], name))
                {
                    return i;
                }
            }

            return int.MaxValue;
        }

        private static int IndexOfRoot(string name)
        {
            for (var i = 0; i < Parsed.Length; i++)
            {
                if (SameName(Parsed[i].Name, name))
                {
                    return i;
                }
            }

            return -1;
        }

        /// <summary>Порівняння назв без огляду на тип апострофа: у макеті стоїть \u2019, у базі — \'.</summary>
        public static bool SameName(string left, string right) =>
            string.Equals(left.Replace('\u2019', '\''), right.Replace('\u2019', '\''),
                          StringComparison.OrdinalIgnoreCase);
    }
